process.env.PDFAPP_TARGET='pdf-studio';
const {launch,WORK}=require('./harness');
(async()=>{const {browser,page}=await launch();await page.waitForTimeout(2300);
await page.setInputFiles('#fAdd',[WORK+'/samples/rowform.pdf']);await page.waitForTimeout(1500);
await page.locator('.card').first().locator('.mnb').click();await page.locator('#menuBtns button',{hasText:'ページ編集'}).click();await page.waitForTimeout(3000);
const fr=page.frameLocator('#formFrame'),f=page.frames().find(x=>x!==page.mainFrame());
await fr.locator('[data-m=text]').click();const ov=await fr.locator('#ov').boundingBox(),k=ov.width/420;
const draw=async(x,y,w,h)=>{await page.mouse.move(ov.x+x*k,ov.y+y*k);await page.mouse.down();await page.mouse.move(ov.x+(x+w)*k,ov.y+(y+h)*k,{steps:5});await page.mouse.up();await page.waitForTimeout(500);const it=(await f.evaluate(()=>window.pdfEditorDebug.items())).pop();await fr.locator('[data-m=text]').click();return it.size;};
console.log('Addressの行(12pt)の欄 200×34:',await draw(90,125,200,34),'pt');
console.log('題(30pt)の行 200×34:',await draw(210,25,200,34),'pt');
console.log('注(7pt)の行 200×26:',await draw(210,260,200,26),'pt');
console.log('何もない行 200×34:',await draw(210,180,200,34),'pt (ページの中央値)');
await browser.close();})();
