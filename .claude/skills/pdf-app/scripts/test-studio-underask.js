// 文字の上に枠を作ったとき: 元の文字を拾って、そのまま入力枠に入れる(案内の枠は出さない)。確定のとき、元の文字○○を消去するか、残して文字を置くかを聞く
process.env.PDFAPP_TARGET='pdf-studio';
const fs=require('fs'),{execSync}=require('child_process');const {launch,WORK}=require('./harness');
(async()=>{const {browser,page}=await launch();const errs=[];page.on('pageerror',e=>errs.push(e.message));page.on('dialog',d=>d.accept());
let ok=true;const chk=(n,c)=>{console.log((c?'OK  ':'NG  ')+n);if(!c)ok=false;};
const open=async()=>{await page.reload();await page.waitForTimeout(2300);await page.setInputFiles('#fAdd',[WORK+'/samples/studio_A4.pdf']);await page.waitForTimeout(1500);
  await page.locator('.card').first().locator('.mnb').click();await page.locator('#menuBtns button',{hasText:'ページ編集'}).click();await page.waitForTimeout(3500);
  const fr=page.frameLocator('#formFrame'),f=page.frames().find(x=>x!==page.mainFrame());
  await f.evaluate(()=>{window.__noUnderAsk=false;window.__keepAns=undefined;});
  await fr.locator('[data-m=sel]').click();await page.waitForTimeout(600);
  const rb=await fr.locator('#ov .run').first().boundingBox();await fr.locator('[data-m=text]').click();await page.waitForTimeout(300);
  await page.mouse.move(rb.x-6,rb.y-6);await page.mouse.down();await page.mouse.move(rb.x+rb.width+6,rb.y+rb.height+6,{steps:6});await page.mouse.up();await page.waitForTimeout(1200);
  return{fr,f};};
const save=async(fr)=>{await fr.locator('#embSave').click();await page.waitForTimeout(3000);fs.writeFileSync('/tmp/ua.pdf',Buffer.from(await page.evaluate(()=>Array.from(window.pdfStudioDebug.bytes(0)))));return execSync('pdftotext -f 1 -l 1 /tmp/ua.pdf -').toString();};
let {fr,f}=await open();
chk('枠を作っても、案内の枠は出ない',await fr.locator('#underAsk').count()===0);
let t=await f.evaluate(()=>window.pdfEditorDebug.items().map(x=>x.type+':'+x.txt));
chk('元の文字が、そのまま入力枠に入っている(訂正の枠): '+t,t.length>=1&&t.every(x=>x.startsWith('fix:'))&&/A-1/.test(t.join()));
chk('自由編集は、枠を選んだときのボタンから使える',await fr.locator('#sFree').isVisible());
await page.keyboard.press('End');await page.keyboard.type('ZZ',{delay:30});await page.waitForTimeout(300);
await fr.locator('#embHead #sClose').click();await page.waitForTimeout(1200);
chk('確定すると、元の文字を消去すると表示される(元の文字も見える)',await fr.locator('#keepAsk').count()===1&&/A-1/.test(await fr.locator('#keepAsk').innerText())&&/消去/.test(await fr.locator('#keepAsk').innerText()));
await fr.locator('#keepAsk button',{hasText:'いいえ'}).click();await page.waitForTimeout(2500);
let txt=await save(fr);
chk('「いいえ」: 元の文字(A-1)は残り、入力した文字(ZZ)も入る',/A-1/.test(txt)&&/ZZ/.test(txt));
({fr,f}=await open());
await page.keyboard.press('End');await page.keyboard.type('ZZ',{delay:30});await page.waitForTimeout(300);
await fr.locator('#embHead #sClose').click();await page.waitForTimeout(1200);
await fr.locator('#keepAsk button',{hasText:'はい'}).click();await page.waitForTimeout(2500);
txt=await save(fr);
chk('「はい」: 元の文字は消去され、置き換わる(A-1XYZ型: ZZ入り・元のA-1だけは残らない)',/ZZ/.test(txt)&&!/A-1\s*\n/.test(txt.replace(/A-1ZZ/,'')));
console.log('errs',errs.slice(0,3));await browser.close();process.exit(ok&&!errs.length?0:1);})();
