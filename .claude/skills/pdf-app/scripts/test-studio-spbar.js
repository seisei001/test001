// ページ編集: 枠の真上の「行間・字間」バーで、行間と字間が変わる/バーの位置がぶれない
process.env.PDFAPP_TARGET='pdf-studio';
const {launch,WORK}=require('./harness');
(async()=>{
  const {browser,page}=await launch();const errs=[];page.on('pageerror',e=>errs.push(e.message));
  await page.waitForTimeout(2300);
  await page.setInputFiles('#fAdd',[WORK+'/samples/studio_A4.pdf']);await page.waitForTimeout(1500);
  await page.locator('.card').first().locator('.mnb').click();
  await page.locator('#menuBtns button',{hasText:'ページ編集'}).click();await page.waitForTimeout(3000);
  const fr=page.frameLocator('#formFrame'),f=page.frames().find(x=>x!==page.mainFrame());
  let ok=true;const chk=(n,c)=>{console.log((c?'OK  ':'NG  ')+n);if(!c)ok=false;};
  await fr.locator('[data-m=sel]').click();await page.waitForTimeout(500);
  const rb=await fr.locator('#ov .run').first().boundingBox();await page.mouse.click(rb.x+rb.width/2,rb.y+rb.height/2);await page.waitForTimeout(600);
  const it=()=>f.evaluate(()=>{const i=window.pdfEditorDebug.items().filter(x=>x.type==='fix').pop();return {lh:i.lh,ls:i.ls||0,vw:i.vw};});
  const a=await it();
  const bar=fr.locator('.spbar');const bb=await bar.boundingBox(),eb=await fr.locator('.ibox.on').boundingBox(),gb=await fr.locator('.grip').boundingBox(),hb=await fr.locator('.hdl.mv').boundingBox();
  chk('バーが枠の真上にある',await bar.count()===1&&bb.y+bb.height<=eb.y+1);
  chk('バーは✥の右から出る(重ならない)',bb.x>=hb.x+hb.width-1);
  chk('バーは枠から離れない(すき間が2px以内)',Math.abs(eb.y-(bb.y+bb.height))<=2);
  chk('右下の矢印と重ならない',gb.y>bb.y+bb.height||gb.x>bb.x+bb.width||gb.x+gb.width<bb.x);
  const set=(sel,v)=>f.evaluate(([s,v])=>{const e=document.querySelector(s);e.value=v;e.dispatchEvent(new Event('input',{bubbles:true}));},[sel,v]);
  await set('.spbar .r1','2');await set('.spbar .r2','5');
  const b=await it();chk(`行間・字間が変わる(${a.lh}→${b.lh}, ${a.ls}→${b.ls})`,b.lh===2&&b.ls===5);
  chk('幅は、字間を広げたぶん広がる(縮まない)',b.vw>=a.vw);
  chk('バーは残っている',await bar.count()===1);
  const lb=await bar.locator('label').evaluateAll(l=>l.map(e=>e.getBoundingClientRect()).map(r=>[r.x,r.y]));
  chk('行間と字間は縦に並ぶ(上:行間 下:字間)',lb.length===2&&lb[1][1]>lb[0][1]&&Math.abs(lb[1][0]-lb[0][0])<2);
  const k=await f.evaluate(()=>document.querySelector('.ibox.on').getBoundingClientRect().width/window.pdfEditorDebug.items().filter(x=>x.type==='fix').pop().vw);
  const bh=(await bar.boundingBox()).height;
  chk(`バーの文字は10ptの大きさ(文字の高さ=10pt×表示倍率${k.toFixed(2)}): バーの高さ ${bh.toFixed(0)}px`,Math.abs(bh/(await bar.evaluate(e=>e.offsetHeight))-10*k/11)<0.02);
  await f.evaluate(()=>document.documentElement.style.setProperty('--zs','0.25'));
  chk('画面の拡大率(--zs)には左右されない',Math.abs((await bar.boundingBox()).height-bh)<1);
  console.log('JSエラー:',errs.length,errs.slice(0,2));await browser.close();process.exit(ok?0:1);
})();
